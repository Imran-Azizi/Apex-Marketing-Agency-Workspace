export function composeInsight(signal) {
  const kind = signal.kind;
  const sw = signal.strengthOrWeakness || 'OPPORTUNITY';
  const actionMap = ACTION_TEMPLATES[kind] || {};
  const recommendedAction =
    actionMap[sw] ||
    actionMap.RISK ||
    actionMap.WEAKNESS ||
    actionMap.OPPORTUNITY ||
    'وضعیت را با داده‌های سیستم بررسی و اقدام مشخص تعیین کنید.';

  const facts = (signal.facts || []).join(' · ');
  const title = `${KIND_LABELS[kind] || kind} — ${SWOT_LABELS[sw] || sw}`;
  const reason = facts || `سیگنال ${CATEGORY_LABELS[signal.category] || signal.category} شناسایی شد.`;

  return {
    title,
    reason,
    strengthOrWeakness: sw,
    recommendedAction,
    actionPlan: PLAN_TEMPLATES[kind] || null,
    weeklyStrategy:
      kind === 'WEEKLY_STRATEGY'
        ? 'تمرکز هفته: بهبود جریان نقدی، تسریع تبدیل مسیر فروش، تقویت بازاریابی، و کاهش تأخیر پروژه‌ها.'
        : kind === 'MONTHLY_STRATEGY'
          ? 'تمرکز ماه: دستیابی به اهداف درآمد و سود، جذب مشتری جدید، و اجرای استراتژی‌های بازاریابی.'
          : null,
    monthlyStrategy:
      kind === 'MONTHLY_STRATEGY'
        ? 'برنامه ماهانه: بازنگری اهداف، تخصیص منابع به فروش و بازاریابی، و پیگیری هفتگی پیشرفت.'
        : null,
  };
}
